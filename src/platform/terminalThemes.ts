const SCHEME_INDEX: ReadonlyMap<string, TerminalColorScheme> = new Map(
  TERMINAL_COLOR_SCHEMES.map((scheme) => [scheme.id, scheme]),
);

/** 按 id 找内置配色；`auto` / 未知 id 一律返回 null（调用方回落应用主题）。 */
export function findTerminalColorScheme(id: string | undefined | null): TerminalColorScheme | null {
  if (!id || id === TERMINAL_THEME_AUTO) return null;
  return SCHEME_INDEX.get(id) ?? null;
}

/** 内置配色 → 内核主题：光标反底色 = 背景，灰阶按前景/背景重算（浅底主题）。 */
export function schemeToTerminalTheme(scheme: TerminalColorScheme): TerminalTheme {
  return {
    background: scheme.background,
    foreground: scheme.foreground,
    cursor: scheme.cursor,
    cursorAccent: scheme.background,
    selectionBackground: scheme.selection,
    black: scheme.black,
    red: scheme.red,
    green: scheme.green,
    yellow: scheme.yellow,
    blue: scheme.blue,
    magenta: scheme.magenta,
    cyan: scheme.cyan,
    white: scheme.white,
    brightBlack: scheme.brightBlack,
    brightRed: scheme.brightRed,
    brightGreen: scheme.brightGreen,
    brightYellow: scheme.brightYellow,
    brightBlue: scheme.brightBlue,
    brightMagenta: scheme.brightMagenta,
    brightCyan: scheme.brightCyan,
    brightWhite: scheme.brightWhite,
    extendedAnsi: buildExtendedAnsi(scheme.foreground, scheme.background),
  };
}

/** 内置配色下「最小对比度」的默认值：浅底 4.5（拉回可读），深底 1（不干预）。 */
export function schemeContrastRatio(scheme: TerminalColorScheme): number {
  return scheme.light ? 4.5 : 1;
}
